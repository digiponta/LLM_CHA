"""v0.9.6: Evidence-constrained candidate evaluation.

Experimental candidate adapter: caller supplies text generated by an LLM.
Never mistake a templated baseline for an LLM output. No auto-approval.
"""
import re
from difflib import SequenceMatcher

def validate_candidate(question, topic, evidence, candidate):
    reply=str(candidate or "").strip()
    if len(reply)<12 or reply in ("有希広","未学習です"):
        return {"accept":False,"reason":"MALFORMED_OR_SHORT"}
    if not topic or topic not in reply:
        return {"accept":False,"reason":"TOPIC_NOT_GROUNDED"}
    if not evidence:
        # No corpus support for factual interpretation.
        return {"accept":False,"reason":"NO_EVIDENCE"}
    if re.search(r"(?:確実に|証明された|間違いなく|科学的事実)",reply):
        return {"accept":False,"reason":"UNSUPPORTED_CERTAINTY"}
    terms={w for e in evidence for w in re.findall(r"[一-龥ぁ-んァ-ヶ]{2,}",e)}
    overlap=any(w in reply for w in terms if len(w)>=3)
    similarity=max((SequenceMatcher(None,reply,e).ratio() for e in evidence),default=0.0)
    if not overlap and similarity<0.24:
        return {"accept":False,"reason":"LOW_EVIDENCE_ALIGNMENT"}
    if "未検証" not in reply and "考察" not in reply and "原文" not in reply:
        return {"accept":False,"reason":"MISSING_UNVERIFIED_DISCLOSURE"}
    return {"accept":True,"reason":"HEURISTIC_EVIDENCE_ALIGNMENT"}

def compare(baseline, candidate, question, topic, evidence):
    result=validate_candidate(question,topic,evidence,candidate)
    return {"status":"ACCEPT_CANDIDATE" if result["accept"] else "KEEP_BASELINE",
            "candidate_gate":result,"baseline":baseline,
            "candidate":candidate,"selected":candidate if result["accept"] else baseline,
            "experiment_only":True,"verified":False,"train_ready":False}
